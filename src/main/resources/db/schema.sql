-- ========================================================
-- Multi-Threaded Banking System: Normalized Schema DDL
-- Compatible with PostgreSQL and H2 in PostgreSQL mode
-- ========================================================

DROP TABLE IF EXISTS FAILED_TRANSACTION CASCADE;
DROP TABLE IF EXISTS TRANSACTION_AUDIT CASCADE;
DROP TABLE IF EXISTS TRANSACTION CASCADE;
DROP TABLE IF EXISTS ACCOUNT CASCADE;
DROP TABLE IF EXISTS CUSTOMER CASCADE;

-- 1. CUSTOMER Table
CREATE TABLE CUSTOMER (
    customer_id VARCHAR(36) PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone VARCHAR(20),
    created_at TIMESTAMP NOT NULL
);

-- 2. ACCOUNT Table
CREATE TABLE ACCOUNT (
    account_id VARCHAR(36) PRIMARY KEY,
    customer_id VARCHAR(36) NOT NULL,
    account_number VARCHAR(30) NOT NULL UNIQUE,
    balance DECIMAL(15, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_account_customer FOREIGN KEY (customer_id) REFERENCES CUSTOMER(customer_id),
    CONSTRAINT chk_account_balance CHECK (balance >= 0.00),
    CONSTRAINT chk_account_status CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED'))
);

-- 3. TRANSACTION Table
CREATE TABLE TRANSACTION (
    transaction_id VARCHAR(64) PRIMARY KEY,
    source_account VARCHAR(36),
    destination_account VARCHAR(36),
    amount DECIMAL(15, 2) NOT NULL,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_txn_source FOREIGN KEY (source_account) REFERENCES ACCOUNT(account_id),
    CONSTRAINT fk_txn_dest FOREIGN KEY (destination_account) REFERENCES ACCOUNT(account_id),
    CONSTRAINT chk_txn_amount CHECK (amount > 0.00),
    CONSTRAINT chk_txn_type CHECK (type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    CONSTRAINT chk_txn_status CHECK (status IN ('SUCCESS', 'FAILED', 'REJECTED'))
);

-- 4. TRANSACTION_AUDIT Table
CREATE TABLE TRANSACTION_AUDIT (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(64) NOT NULL,
    operation_type VARCHAR(20) NOT NULL,
    thread_name VARCHAR(100) NOT NULL,
    duration_ms BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    recorded_at TIMESTAMP NOT NULL
);

-- 5. FAILED_TRANSACTION Table
CREATE TABLE FAILED_TRANSACTION (
    failure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(64) NOT NULL,
    error_category VARCHAR(50) NOT NULL,
    error_code VARCHAR(50) NOT NULL,
    failure_reason VARCHAR(500) NOT NULL,
    failed_at TIMESTAMP NOT NULL
);

-- Workload-Justified Indexes
CREATE INDEX idx_account_customer ON ACCOUNT(customer_id);
CREATE INDEX idx_txn_source_created ON TRANSACTION(source_account, created_at);
CREATE INDEX idx_txn_dest_created ON TRANSACTION(destination_account, created_at);
CREATE INDEX idx_txn_status ON TRANSACTION(status);
CREATE INDEX idx_txn_type_created ON TRANSACTION(type, created_at);
CREATE INDEX idx_audit_txnid ON TRANSACTION_AUDIT(transaction_id);
CREATE INDEX idx_failed_txnid ON FAILED_TRANSACTION(transaction_id);
CREATE INDEX idx_failed_category ON FAILED_TRANSACTION(error_category);
